/** [chapter number, verbatim quotes from that chapter that ground the activity] */
export type RefInput = [number, string[]];

export interface ActivityContext {
  module: SourceModule;
  lessonNo: number;
}

const lessonOf = (ctx: ActivityContext) => ctx.module.lessons[ctx.lessonNo - 1];

function refs(ctx: ActivityContext, inputs: RefInput[], sourceIds: string[]): Wave2ChapterRef[] {
  const lesson = lessonOf(ctx);
  return inputs.map(([number, quotes]) => ({
    sourceModuleKey: ctx.module.moduleKey,
    lessonTitle: lesson.lessonTitle,
    chapterTitle: lesson.chapters[number - 1].title,
    chapterIndex: number - 1,
    sourceIds,
    grounding: quotes.map((quote) => `\u201c${quote}\u201d`).join(' '),
  }));
}

interface Shared {
  id: string;
  ctx: ActivityContext;
  refs: RefInput[];
  sourceIds: string[];
  title: string;
  objective: string;
  summary: string;
}

function base(input: Shared, type: Wave2Activity['type']) {
  const moduleNo = Number(input.ctx.module.moduleId.replace(/\D/g, ''));
  const lesson = lessonOf(input.ctx);
  const sourceRefs = refs(input.ctx, input.refs, input.sourceIds);
  return {
    activityId: `pa-m${moduleNo}-l${input.ctx.lessonNo}-${input.id}`,
    industryId: 'professional-audit',
    moduleId: input.ctx.module.moduleId,
    lessonId: `${input.ctx.module.moduleKey}::${lesson.lessonTitle}`,
    chapterId: `${input.ctx.module.moduleKey}::${lesson.lessonTitle}::${sourceRefs[0].chapterTitle}`,
    type,
    title: input.title,
    learningObjective: input.objective,
    summary: input.summary,
    sourceRefs,
  };
}

export function matching(input: Shared & { promptLabel: string; answerLabel: string; pairs: Array<[string, string, string, string]> }): Wave2Activity {
  const pairs = input.pairs.map(([prompt, answer, explanation, hint]) => ({
    id: `pair-${slug(prompt)}`,
    promptId: `prompt-${slug(prompt)}`,
    answerId: `answer-${slug(answer)}`,
    explanation,
    hint,
  }));
  return {
    ...base(input, 'concept-matching'),
    type: 'concept-matching',
    instructions: PAIR_INSTRUCTIONS,
    promptLabel: input.promptLabel,
    answerLabel: input.answerLabel,
    items: {
      prompts: input.pairs.map(([prompt]) => ({ id: `prompt-${slug(prompt)}`, text: prompt })),
      answers: [...input.pairs].reverse().map(([, answer]) => ({ id: `answer-${slug(answer)}`, text: answer })),
    },
    pairs,
  };
}

export function sorting(input: Shared & { categories: Array<[string, string, string]>; items: Array<[string, string, string, string]> }): Wave2Activity {
  return {
    ...base(input, 'category-sorting'),
    type: 'category-sorting',
    instructions: SORT_INSTRUCTIONS,
    categories: input.categories.map(([id, label, description]) => ({ id, label, description })),
    items: input.items.map(([text, categoryId, explanation, hint]) => ({ id: `item-${slug(text)}`, text, categoryId, explanation, hint })),
  };
}

export function sequence(input: Shared & { evidence: string; steps: Array<[string, string, string]> }): Wave2Activity {
  const ordered = input.steps.map(([text, explanation, hint]) => ({ id: `step-${slug(text)}`, text, explanation, hint }));
  const scrambled = ordered.map((_, index) => ordered[(index * 2 + 1) % ordered.length]);
  const items = new Set(scrambled).size === ordered.length ? scrambled : [...ordered].reverse();
  return {
    ...base(input, 'sequence-builder'),
    type: 'sequence-builder',
    instructions: SEQUENCE_INSTRUCTIONS,
    isSequentialProcess: true,
    sequenceEvidence: input.evidence,
    items,
    correctSequence: ordered.map((step) => step.id),
  };
}
