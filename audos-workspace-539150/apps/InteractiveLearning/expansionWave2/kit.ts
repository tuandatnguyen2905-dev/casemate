// Declarative builders for wave-2 decks and activities. A deck resolves to the plain
// FlashcardDeckContent shape and an activity to the engine's activity shape (see ../flashcards/models.ts
// and ../matchSort/types.ts); this only removes boilerplate around chapters, source mapping and IDs.

import type { FlashcardContent, FlashcardDeckContent, SourceRef } from '../flashcards/models';
import type { CardCategory, SourceModule, Wave2Activity, Wave2ChapterRef } from './types';

export const READ_AT = '2026-11-08';

export const PAIR_INSTRUCTIONS = 'Select an item on the left, then select the item on the right that matches it. On a computer you can also drag a left item onto its match. Pair every item, then check your answers.';
export const SORT_INSTRUCTIONS = 'Select an item, then choose the group it belongs to. On a computer you can also drag an item into a group. You can move items between groups until you check.';
export const SEQUENCE_INSTRUCTIONS = 'Put the stages in order from first to last. Use the Move up and Move down buttons, press Alt with the arrow keys, or drag a stage on a computer. Check when you are ready.';

const CATEGORY: Record<string, CardCategory> = {
  C: 'Concept Recall',
  M: 'Mechanism Understanding',
  F: 'Financial Literacy',
  B: 'Business Application',
  D: 'Compare & Differentiate',
};

/** Card category by card ID, filled as decks are defined. Not part of the flashcard model. */
export const CARD_CATEGORIES = new Map<string, CardCategory>();

export const slug = (text: string, words = 6) => text.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim().split(' ').slice(0, words).join('-');
const chapterIdFor = (lessonId: string, number: number) => `${lessonId}-ch${String(number).padStart(2, '0')}`;

/** [slug, chapter number, category code, front, back, explanation, practical example, key terms, [chapter number, verbatim excerpt][]] */
export type CardTuple = [string, number, keyof typeof CATEGORY, string, string, string, string, string[], Array<[number, string]>];

export interface LessonDeckInput {
  module: SourceModule;
  lessonNo: number;
  description: string;
  cards: CardTuple[];
  notes?: string[];
}

export function lessonDeck(input: LessonDeckInput): FlashcardDeckContent {
  const { module, lessonNo } = input;
  const lesson = module.lessons[lessonNo - 1];
  const moduleNo = Number(module.moduleId.replace(/\D/g, ''));
  const lessonId = `pa-m${moduleNo}-l${lessonNo}`;
  const offset = module.lessons.slice(0, lessonNo - 1).reduce((sum, item) => sum + item.chapters.length, 0);
  const next = module.lessons[lessonNo];
  const industryId = 'professional-audit';
  const chapters = lesson.chapters.map((chapter, index) => ({
    chapterId: chapterIdFor(lessonId, index + 1),
    number: index + 1,
    title: chapter.title,
    sourceTitle: `${String(offset + index + 1).padStart(2, '0')} ${chapter.title}`,
  }));
  const sourceRef = (number: number, excerpt: string): SourceRef => ({ file: module.file, chapterId: chapterIdFor(lessonId, number), excerpt });
  const cards: FlashcardContent[] = input.cards.map(([id, ch, cat, front, back, explanation, example, terms, refs]) => {
    const cardId = `${lessonId}-${id}`;
    CARD_CATEGORIES.set(cardId, CATEGORY[cat]);
    return {
      cardId,
      deckId: `professional-audit-m${moduleNo}-l${lessonNo}`,
      industryId,
      moduleId: module.moduleId,
      lessonId,
      chapterId: chapterIdFor(lessonId, ch),
      front,
      back,
      explanation,
      practicalExample: example,
      keyTerms: terms,
      sourceRefs: refs.map(([number, excerpt]) => sourceRef(number, excerpt)),
    };
  });
  const flagged = lesson.chapters.filter((chapter) => chapter.alignment === 'mismatch').length;
  return {
    deckId: `professional-audit-m${moduleNo}-l${lessonNo}`,
    title: `Audit & Assurance: ${lesson.lessonTitle}`,
    description: input.description,
    industryId,
    industryLabel: 'Audit & Assurance',
    moduleId: module.moduleId,
    moduleLabel: module.moduleLabel,
    lessonId,
    lessonTitle: lesson.lessonTitle,
    source: {
      file: module.file,
      moduleKey: module.moduleKey,
      lessonTitle: lesson.lessonTitle,
      startMarker: `['${lesson.lessonTitle}',[`,
      endMarker: next ? `['${next.lessonTitle}',[` : '];const topics=',
      chapterMarker: "{title:'",
      readAtSha256: module.readAtSha256,
      readAt: READ_AT,
    },
    chapters,
    cards,
    contentStatus: flagged ? 'Draft / source title-content mismatch flagged' : 'Draft',
    mappingNotes: [
      'Source chapters are generated by auditAssuranceCore.tsx from the module data file: each canonical chapter shows its source item\u2019s text (or an authored detail entry), so one source item can appear in several chapters. Excerpts are verbatim from that displayed text.',
      ...(input.notes ?? []),
    ],
  };
}

