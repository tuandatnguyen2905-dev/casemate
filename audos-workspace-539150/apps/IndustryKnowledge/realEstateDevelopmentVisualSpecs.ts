const npv = (r: number, flows: number[]) => flows.reduce((sum, cf, t) => sum + cf / (1 + r) ** t, 0);
const irr = (flows: number[]) => {
  let lo = -0.9, hi = 1;
  if (npv(lo, flows) * npv(hi, flows) > 0) return NaN;
  for (let i = 0; i < 80; i++) { const mid = (lo + hi) / 2; if (npv(lo, flows) * npv(mid, flows) <= 0) hi = mid; else lo = mid; }
  return (lo + hi) / 2;
};

